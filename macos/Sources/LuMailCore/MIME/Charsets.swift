/// Wandelt Bytes in Text um – mit besonderem Augenmerk auf kyrillische Zeichensätze (Mail.ru).
public enum Charsets {
    public static func decode(_ data: Data, charset rawCharset: String?) -> String {
        let charset = (rawCharset ?? "utf-8").trimmingCharacters(in: CharacterSet(charactersIn: "\"' ")).lowercased()
        switch charset {
        case "utf-8", "utf8", "us-ascii", "ascii", "":
            return utf8OrLatin1(data)
        case "koi8-r", "koi8r", "koi8-u":
            return decodeSingleByte(data, table: koi8rHigh)
        case "windows-1251", "cp1251", "x-cp1251":
            // Eigene Tabelle, weil Foundation unter Linux CP1251 nicht zuverlässig kann.
            return decodeSingleByte(data, table: cp1251High)
        default:
            if let encoding = stringEncoding(for: charset), let text = String(data: data, encoding: encoding) {
                return text
            }
            return utf8OrLatin1(data)
        }
    }

    static func utf8OrLatin1(_ data: Data) -> String {
        if let text = String(data: data, encoding: .utf8) { return text }
        return String(data: data, encoding: .isoLatin1) ?? String(decoding: data, as: UTF8.self)
    }

    static func stringEncoding(for charset: String) -> String.Encoding? {
        switch charset {
        case "iso-8859-1", "latin1", "iso8859-1", "l1": return .isoLatin1
        case "iso-8859-2", "latin2": return .isoLatin2
        case "windows-1250", "cp1250": return .windowsCP1250
        case "windows-1252", "cp1252": return .windowsCP1252
        case "windows-1253", "cp1253": return .windowsCP1253
        case "windows-1254", "cp1254": return .windowsCP1254
        case "utf-16", "utf16": return .utf16
        case "iso-2022-jp": return .iso2022JP
        case "shift_jis", "shift-jis", "sjis": return .shiftJIS
        case "euc-jp": return .japaneseEUC
        default:
            #if canImport(Darwin)
            let cfEncoding = CFStringConvertIANACharSetNameToEncoding(charset as CFString)
            guard cfEncoding != kCFStringEncodingInvalidId else { return nil }
            return String.Encoding(rawValue: CFStringConvertEncodingToNSStringEncoding(cfEncoding))
            #else
            return nil
            #endif
        }
    }

    static func decodeSingleByte(_ data: Data, table: [UInt16]) -> String {
        var scalars = String.UnicodeScalarView()
        for byte in data {
            let value = byte < 0x80 ? UInt32(byte) : UInt32(table[Int(byte) - 0x80])
            scalars.append(UnicodeScalar(value) ?? "?")
        }
        return String(scalars)
    }

